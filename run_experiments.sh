#!/usr/bin/env bash
# run_experiments.sh -- reproduce the evaluation table.
#
#   bash run_experiments.sh                > EXPERIMENTS.md
#   bash run_experiments.sh --concuerror   > EXPERIMENTS.md
#
# Explores all 61 message-passing entry points and writes a Markdown table.
# Each row reports what CerlEx explored, and a same-tree "replay"
# counterfactual: the work a stateless explorer would repeat if it re-derived
# every real trace from the initial state instead of retaining prefixes.
#
#   traces      real traces (complete executions)
#   spec        branches built that reached no real trace
#   events      configurations at event boundaries: online / replay
#   steps       local CEK reductions: online / replay
#   saved       (replay - online) / replay
#
# With --concuerror, each entry is also run under Concuerror (must be on PATH)
# and its interleaving count and wall-clock time are reported alongside.
set -euo pipefail
cd "$(dirname "$0")"

WITH_CC=0
[ "${1:-}" = "--concuerror" ] && WITH_CC=1
if [ "$WITH_CC" = 1 ] && ! command -v concuerror >/dev/null 2>&1; then
  echo "concuerror not on PATH; re-run without --concuerror" >&2; exit 1
fi

printf 'Building...' >&2; dune build 2>/dev/null; echo ' ok' >&2
CERLEX=./_build/default/bin/cerlex.exe
OUT=$(mktemp -d); trap 'rm -rf "$OUT"' EXIT

# name | group | main module | entry | extra modules | stdlib
run_one() {
  local name="$1" grp="$2" mod="$3" entry="$4" extra="$5" libs="$6"
  local src core=() lib m start out ms
  if [ -d "benchmarks/$grp" ] && [ -f "benchmarks/$grp/$mod.erl" ]; then src="benchmarks/$grp"
  else src="benchmarks/$grp"; fi
  mkdir -p "$OUT/$grp"
  erlc +to_core -o "$OUT/$grp" "$src/$mod.erl" >/dev/null 2>&1
  for m in $extra; do erlc +to_core -o "$OUT/$grp" "$src/$m.erl" >/dev/null 2>&1; core+=("$OUT/$grp/$m.core"); done
  for lib in $libs; do core+=("otp_stdlib/$lib.core"); done

  start=$(date +%s%3N)
  out=$("$CERLEX" -e "$OUT/$grp/$mod.core" "${core[@]}" -entry "$entry" -quiet -no-io -prefix-stats 2>/dev/null) || true
  ms=$(( $(date +%s%3N) - start ))
  local d p
  d=$(grep -F '[done]'   <<<"$out" || true)
  p=$(grep -F '[prefix]' <<<"$out" || true)
  local f=' & '
  get() { sed -n "s/$1/\1/p" <<<"$2" | tail -1; }
  local real spec on re ons res sav savs
  real=$(get '.*traces: \([0-9]*\) real.*'                    "$d")
  spec=$(get '.*leaves: [0-9]* real, \([0-9]*\) speculative.*' "$p")
  on=$(  get '.*configurations: \([0-9]*\) online.*'           "$p")
  re=$(  get '.*, \([0-9]*\) same-tree stateless.*'            "$p")
  ons=$( get '.*steps: \([0-9]*\) online.*'                    "$p")
  res=$( get '.*steps: [0-9]* online, \([0-9]*\) stateless.*'  "$p")
  sav=$( awk -v a="${on:-0}" -v b="${re:-0}"   'BEGIN{if(b>0)printf "%.1f%%",100*(b-a)/b; else printf "n/a"}')
  savs=$(awk -v a="${ons:-0}" -v b="${res:-0}" 'BEGIN{if(b>0)printf "%.1f%%",100*(b-a)/b; else printf "n/a"}')

  local cc="" ccms=""
  if [ "$WITH_CC" = 1 ]; then
    mkdir -p "$OUT/beam/$grp"
    erlc -o "$OUT/beam/$grp" "$src/$mod.erl" >/dev/null 2>&1
    for m in $extra; do erlc -o "$OUT/beam/$grp" "$src/$m.erl" >/dev/null 2>&1; done
    # Concuerror takes the module and the zero-arity test function.  The
    # entry is either "fun" (module is $mod) or "module:fun".
    local ccmod="$mod" ccent="${entry##*:}" ccout
    start=$(date +%s%3N)
    ccout=$( (cd "$OUT/beam/$grp" && concuerror --module "$ccmod" --test "$ccent" \
        --keep_going --non_racing_system user --instant_delivery false \
        --no_output 2>&1) || true )
    ccms=$(( $(date +%s%3N) - start ))
    # Concuerror redraws its progress line, so strip terminal escapes first.
    cc=$(printf '%s\n' "$ccout" | sed 's/\x1b\[[0-9]*[A-Za-z]//g' \
         | sed -n 's/.*Summary: [0-9]* errors, \([0-9]*\)\/[0-9]*.*/\1/p' | tail -1) || true
  fi

  if [ "$WITH_CC" = 1 ]; then
    printf '| `%s` | %s | %s | %s | %s/%s | %s | %s/%s | %s | %s/%s |\n' \
      "$name" "${real:-?}" "${cc:-?}" "${spec:-0}" "${on:-?}" "${re:-?}" "$sav" \
      "${ons:-?}" "${res:-?}" "$savs" "$ms" "${ccms:-?}"
  else
    printf '| `%s` | %s | %s | %s/%s | %s | %s/%s | %s | %s |\n' \
      "$name" "${real:-?}" "${spec:-0}" "${on:-?}" "${re:-?}" "$sav" \
      "${ons:-?}" "${res:-?}" "$savs" "$ms"
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "${on:-0}" "${re:-0}" "${ons:-0}" "${res:-0}" "$name" >> "$OUT/agg"
  printf '  %-38s %s traces\n' "$name" "${real:-?}" >&2
}

echo '# CerlEx experiments'
echo ''
echo 'Generated by `run_experiments.sh`. Do not edit by hand.'
